// Cold start. Measured 2026-09-09, closing the last item in `CLAUDE.md`'s "Start here now".
//
// THE CLAIM BEING TESTED, quoted so it cannot drift: *"a macro emitting no `CodingKeys` should
// win structurally."* `ROADMAP.md`'s verification table already flags it as "exactly the kind
// of should that this file exists to stop anyone asserting", which is why this arm exists
// rather than the sentence.
//
// WHAT COLD START MEANS HERE, precisely, because the phrase is used for three different things
// and only one of them is measurable in a benchmark harness:
//
//   1. Process start — dyld, image loading, +load. Dominated by linking Foundation at all,
//      not by either decoder. Measured separately below, and labelled as what it is.
//   2. **First decode of a type**, which is what this arm is about: the one-time work a type
//      pays before its second decode is cheap. For Assay that is `swift_once` on the generated
//      `__assayKeyTable` and any rule arrays. For `Codable` it is the `CodingKeys` metadata,
//      the container machinery, and whatever the decoder caches per type.
//   3. Steady state — every other arm in this harness.
//
// THE MEASUREMENT PROBLEM, and how it is dealt with. A type can only be decoded for the first
// time once per process, so a loop measures the *second* decode 999,999 times out of a
// million. The answer is **many distinct types, each decoded exactly once**: 60 structurally
// identical schemas, one sample each, in one process. That is 60 genuine first decodes.
//
// It also means this number is noisier than the steady-state arms — a single sample per type,
// and the first few types also pay for whatever the allocator and the instruction cache were
// not ready for. **The headline is the MEDIAN of the per-type samples, not the total.** Three
// early runs of the total-based version gave 3.3x, 5.8x and 5.2x for the same build, because a
// handful of first-of-everything outliers dominate a sum of sixty samples. The median moves by
// a few percent across the same runs. The total is still printed, beside the median, so the
// spread is visible rather than hidden.
//
// THE ORDER IS ALTERNATED. Running all the Codable types and then all the Assay types would
// give the second group a warm allocator and a warm cache and produce a number that says more
// about the ordering than the decoders. They interleave.
//===----------------------------------------------------------------------===//

import Foundation
import Assay

// 60 distinct types would be 60 near-identical declarations. They are generated by a script
// into `ColdStartTypes.swift`; this file holds the harness and the reasoning.

func runColdStartBenchmarks() {
    print("")
    print("Cold start — first decode of a type, never measured before 2026-09-09")
    print("60 distinct types, ONE sample each, alternated. A type can only be decoded for the")
    print("first time once, so a loop would measure steady state; this is 60 genuine firsts.")
    print("Noisier than every other arm here by construction — one sample per type.")
    print("")

    let json = Array(#"""
        {"id":"cold-0001","name":"a name of ordinary length","count":42,\
        "ratio":0.75,"enabled":true,"note":"a second string field","seq":7,\
        "score":1.5,"visible":false,"tag":"t"}
        """#.replacingOccurrences(of: "\\\n", with: "").utf8)

    var assaySamples: [Double] = []
    var codableSamples: [Double] = []
    let decoder = JSONDecoder()
    let data = Data(json)

    // Alternated: the two decoders see the same allocator and cache state on average.
    for i in 0..<coldStartTypeCount {
        if i % 2 == 0 {
            assaySamples.append(timeOnce { coldAssayDecoders[i](json) })
            codableSamples.append(timeOnce { coldCodableDecoders[i](data, decoder) })
        } else {
            codableSamples.append(timeOnce { coldCodableDecoders[i](data, decoder) })
            assaySamples.append(timeOnce { coldAssayDecoders[i](json) })
        }
    }

    func median(_ xs: [Double]) -> Double {
        let s = xs.sorted()
        return s.count % 2 == 1 ? s[s.count / 2]
                                : (s[s.count / 2 - 1] + s[s.count / 2]) / 2
    }
    let assayMedian = median(assaySamples)
    let codableMedian = median(codableSamples)
    let assayTotal = assaySamples.reduce(0, +)
    let codableTotal = codableSamples.reduce(0, +)

    print(pad("decoder", 14, right: true) + pad("median us", 12) + pad("total us", 12)
          + pad("max us", 10))
    print(String(repeating: "-", count: 48))
    print(pad("JSONDecoder", 14, right: true)
          + pad(String(format: "%.1f", codableMedian / 1000), 12)
          + pad(String(format: "%.0f", codableTotal / 1000), 12)
          + pad(String(format: "%.0f", (codableSamples.max() ?? 0) / 1000), 10))
    print(pad("Assay", 14, right: true)
          + pad(String(format: "%.1f", assayMedian / 1000), 12)
          + pad(String(format: "%.0f", assayTotal / 1000), 12)
          + pad(String(format: "%.0f", (assaySamples.max() ?? 0) / 1000), 10))
    print("")
    print(String(format: "first decode: %.1fx  (median; the total-based ratio swings 3-6x "
                 + "run to run, which is why it is not the headline)",
                 codableMedian / assayMedian))

    // The honest comparison beside it: the SAME types, steady state, so the reader can see how
    // much of the first-decode ratio is one-time work and how much is the decode itself.
    let warmAssay = measure(iterations: 20_000) { _ = coldAssayDecoders[0](json) }
    let warmCodable = measure(iterations: 20_000) { _ = coldCodableDecoders[0](data, decoder) }
    print(String(format: "steady state, same shape: %.1fx  (%.0f ns vs %.0f ns)",
                 warmCodable / warmAssay, warmCodable, warmAssay))
    print("")
    print("Read the DIFFERENCE between those two ratios, not either alone. Subtracting the")
    print("steady-state cost from the first-decode cost leaves the one-time per-type work,")
    print("which is what \"a macro emitting no CodingKeys should win structurally\" claimed.")
}

/// One sample, in nanoseconds. `@inline(never)` on the body's consumer is not needed here —
/// the closures are stored in an array of existentials the optimiser cannot see through, which
/// is a happy accident of needing 60 of them and is stated so nobody "simplifies" it away.
func timeOnce(_ body: () -> Bool) -> Double {
    let start = DispatchTime.now().uptimeNanoseconds
    let ok = body()
    let end = DispatchTime.now().uptimeNanoseconds
    precondition(ok, "a cold-start sample failed to decode; the number would be meaningless")
    return Double(end - start)
}
