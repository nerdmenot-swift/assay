"""Regenerate Sources/AssayBench/ColdStartTypes.swift.

Sixty near-identical type PAIRS, because a type can only be decoded for the first time once
per process — see ColdStartBench.swift's header for why that forces many types rather than
many iterations. Kept as a generator rather than checked-in hand-written repetition so the
count can change without sixty edits, and so the two halves cannot drift apart by hand.

    python3 Benchmarks/gen-coldstart.py > Benchmarks/Sources/AssayBench/ColdStartTypes.swift

The two halves must stay semantically identical — same field names, same wire keys, same
types — or the comparison measures the shapes rather than the decoders.
"""

N = 60

FIELDS = [
    ("id", "String"),
    ("name", "String"),
    ("count", "Int"),
    ("ratio", "Double"),
    ("enabled", "Bool"),
    ("note", "String"),
    ("seq", "Int"),
    ("score", "Double"),
    ("visible", "Bool"),
    ("tag", "String"),
]

out = []
out.append(f'''// Assay — a decoder for Swift that tells you what went wrong.
// Copyright 2026 Srinivas Iyer. Licensed under the Apache License, Version 2.0.
// See LICENSE and NOTICE at the repository root for terms.

// GENERATED by Benchmarks/gen-coldstart.py. Do not edit by hand.
//
// {N} structurally identical pairs of types, so `ColdStartBench.swift` has {N} genuine FIRST
// decodes to sample rather than one. See that file for why a loop cannot measure this.
//
// The two halves are semantically identical: same field names, same wire keys, same types.
// Only the conformance mechanism differs, which is the whole comparison.

import Foundation
import Assay

let coldStartTypeCount = {N}
''')

body = "\n".join(f"    var {n}: {t}" for n, t in FIELDS)

for i in range(N):
    out.append(f'''
@Schema(keys: .snakeCase)
struct ColdA{i} {{
{body}
}}

struct ColdC{i}: Decodable {{
{body}
}}
''')

# `@Sendable` on the element type: these are file-scope `let`s, and Swift 6 strict concurrency
# requires the stored closures to be Sendable for that to be legal.
out.append("\nlet coldAssayDecoders: [@Sendable ([UInt8]) -> Bool] = [\n")
for i in range(N):
    out.append(f"    {{ (try? ColdA{i}.parse(json: $0)) != nil }},\n")
out.append("]\n\nlet coldCodableDecoders: [@Sendable (Data, JSONDecoder) -> Bool] = [\n")
for i in range(N):
    out.append(f"    {{ (try? $1.decode(ColdC{i}.self, from: $0)) != nil }},\n")
out.append("]\n")

print("".join(out), end="")
