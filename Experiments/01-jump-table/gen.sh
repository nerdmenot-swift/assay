#!/bin/bash
# Generate the experiment-1 switch variants.
#
#   gen.sh const <N>   -> switches.swift       arms produce distinct CONSTANTS
#   gen.sh code  <N>   -> switches_code.swift  arms call distinct FUNCTIONS
#
# METHOD NOTE, and it matters if anyone re-runs this. The first attempt used
# `acc += 1000 + i` case bodies. Those are affine in the index, so SimplifyCFG folded the
# entire switch into arithmetic (`switch.offset`) and erased the dispatch — the question
# became unanswerable. Case bodies must be non-affine.
#
# The `code` variant is the one that answers Assay's actual question: real field-dispatch
# arms run *different code* (decode an Int here, a String there), so no constant lookup
# table can represent them and LLVM must emit a jump table or a comparison chain.
set -euo pipefail
cd "$(dirname "$0")"

MODE=${1:-code}
N=${2:-50}

# Deterministic, non-affine constants. Knuth multiplicative hash mod a prime.
konst() { awk -v i="$1" 'BEGIN{ printf "%d", (i * 2654435761) % 1000003 }'; }

emit_enum() {
  echo "public enum Field${N}: UInt8 {"
  for ((i = 0; i < N; i++)); do echo "    case f${i}"; done
  echo "    case unknown"
  echo "}"
  echo
}

if [ "$MODE" = "const" ]; then
  {
    cat <<EOF
// Experiment #1a — constant-producing arms (GENERATED by gen.sh, do not edit)
//
// Case bodies are non-affine in the index on purpose: with affine bodies LLVM's
// SimplifyCFG folds the whole switch into arithmetic and the question is unanswerable.

EOF
    echo "@inline(never)"
    echo "public func dispatchUInt8(_ i: UInt8, _ acc: inout Int) {"
    echo "    switch i {"
    for ((i = 0; i < N; i++)); do echo "    case ${i}: acc = acc &* 31 &+ $(konst $i)"; done
    echo "    default: acc = acc &* 31 &+ 7"
    echo "    }"
    echo "}"
    echo
    emit_enum
    echo "@inline(never)"
    echo "public func dispatchEnum(_ f: Field${N}, _ acc: inout Int) {"
    echo "    switch f {"
    for ((i = 0; i < N; i++)); do echo "    case .f${i}: acc = acc &* 31 &+ $(konst $i)"; done
    echo "    case .unknown: acc = acc &* 31 &+ 7"
    echo "    }"
    echo "}"
    echo
    # Sparse integer cases — the length-bucket fallback shape from §4.3.
    # Stride 5 keeps the largest case (49*5 = 245) inside UInt8.
    echo "@inline(never)"
    echo "public func dispatchSparse(_ i: UInt8, _ acc: inout Int) {"
    echo "    switch i {"
    for ((i = 0; i < N; i++)); do echo "    case $((i * 5)): acc = acc &* 31 &+ $(konst $i)"; done
    echo "    default: acc = acc &* 31 &+ 7"
    echo "    }"
    echo "}"
  } > switches.swift
  echo "wrote switches.swift ($N arms, constant bodies)"
else
  {
    echo "// Experiment #1b — divergent code per arm (GENERATED by gen.sh, do not edit)"
    echo
    for ((i = 0; i < N; i++)); do
      echo "@inline(never) func sink${i}(_ a: inout Int) { a = a &* 31 &+ $(konst $i) }"
    done
    echo "@inline(never) func sinkDefault(_ a: inout Int) { a = a &* 31 &+ 7 }"
    echo
    emit_enum
    echo "@inline(never)"
    echo "public func codeDispatchUInt8(_ i: UInt8, _ acc: inout Int) {"
    echo "    switch i {"
    for ((i = 0; i < N; i++)); do echo "    case ${i}: sink${i}(&acc)"; done
    echo "    default: sinkDefault(&acc)"
    echo "    }"
    echo "}"
    echo
    echo "@inline(never)"
    echo "public func codeDispatchEnum(_ f: Field${N}, _ acc: inout Int) {"
    echo "    switch f {"
    for ((i = 0; i < N; i++)); do echo "    case .f${i}: sink${i}(&acc)"; done
    echo "    case .unknown: sinkDefault(&acc)"
    echo "    }"
    echo "}"
  } > switches_code.swift
  echo "wrote switches_code.swift ($N arms, divergent code)"
fi
